"""Sync check: one master year value drives counter, population and state colours. Writes docs/sync_report.md."""
import math, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mapviz import video2 as V
r = V.Renderer()
D = V.data()
SER = D["pop"][V.FOCUS] if V.FOCUS else D["us_total"]
rows = ["# Sync report (generated by scripts/sync_check.py)", "",
        "Counter, U.S. population and state colours all derive from the master year Y(t). The colour fade starts at the exact frame where the counter reaches the census year.", "",
        "| Census | Counter one frame before | Counter at run end | Fade p one frame before | Fade p at run end | Fade p +0.75 s | Fade p +1.5 s | Population at run end = Census total |",
        "|---|---|---|---|---|---|---|---|"]
bad = 0
for i in range(1, V.NB):
    t0 = V.B0 + V.BLK * (i - 1)
    fr_end = int(round((t0 + V.RUN) * V.FPS))
    def state(fr):
        t = fr / V.FPS; ii, lt = r.locate(t)
        Y = r.year_at(ii, lt)
        f = min(lt / V.RUN, 1.0)
        y0, y1 = V.YEARS[ii - 1], V.YEARS[ii]
        yshow = y1 if f >= 1 else int(math.floor(Y + 1e-6))
        tot = int(round(SER[y0] + (SER[y1] - SER[y0]) * f))
        return ii, yshow, tot, r.fade_p(ii, lt)
    a = state(fr_end - 1); b = state(fr_end); c = state(fr_end + int(0.75 * V.FPS)); d = state(fr_end + int(1.5 * V.FPS))
    y1 = V.YEARS[i]
    ok = (b[1] == y1 and a[1] == y1 - 1 and a[3] == 0 and b[3] == 0 and 0 < c[3] < 1 and abs(d[3] - 1) < 1e-9 and b[2] == SER[y1])
    bad += (not ok)
    rows.append(f"| {y1} | {a[1]} | {b[1]} | {a[3]:.2f} | {b[3]:.2f} | {c[3]:.2f} | {d[3]:.2f} | {'yes' if b[2] == SER[y1] else 'NO'} {'' if ok else '  <-- FAIL'} |")
rows += ["", f"Result: {f'all {V.NB - 1} census transitions in sync' if not bad else str(bad) + ' FAILED'}."]
Path(__file__).resolve().parent.parent.joinpath("docs/sync_report.md").write_text("\n".join(rows), encoding="utf-8")
print("\n".join(rows[-5:]))
assert not bad
