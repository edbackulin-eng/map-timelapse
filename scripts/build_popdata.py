"""Build the verified dataset for the trial video and write docs/verify_report.md.

Sources (all U.S. Census Bureau, www2.census.gov):
  1790-1900 state populations: Forstall, "Population of States and Counties of the United States: 1790-1990"
     (1996), Part II  (OCR text, validated: sum of states == printed U.S. total for every year)
  1910-2020 state populations + density: apportionment.csv (2020 Census apportionment data, digital)
  state land area: sum of 2020 Gazetteer county land areas (ALAND_SQMI)
  mean centre of population 1790-2020: COP2020_documentation.pdf, Table 1
"""
import csv, json, math, re, sys
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from mapviz.choro import STATE_NAMES  # noqa: E402

YEARS = list(range(1790, 2021, 10))
NAME2AB = {v: k for k, v in STATE_NAMES.items()}
report = []
def R(s=""): report.append(s); print(s)

# ---- 1790-1900 from Forstall OCR (parsed by parse_hist.py) ----
forst = json.load(open(root / "data/hist/forstall_parsed.json"))
forst = {k: {int(y): v for y, v in d.items()} for k, d in forst.items()}
corrections = []
forst["Nebraska"].pop(1810, None)
corrections.append("Nebraska 1810: stray OCR artefact ('7') removed - Nebraska had no 1810 census count; "
                   "restores the state sum to the printed U.S. total 7,239,881.")
assert forst["Arizona"][1890] == 38243
forst["Arizona"][1890] = 88243
corrections.append("Arizona 1890: OCR read 38,243; correct value 88,243 (the state sum was exactly 50,000 below the "
                   "printed U.S. total 62,979,766; with 88,243 it matches).")
R("# Verification report (generated by scripts/build_popdata.py)\n")
R("## 1. 1790-1900 state table (Forstall 1996, Census Bureau) - sum of states vs printed U.S. total")
R("| Year | Sum of states | Printed U.S. total | Diff |"); R("|---|---|---|---|")
for y in range(1790, 1901, 10):
    s = sum(v.get(y, 0) for k, v in forst.items() if k != "United States")
    us = forst["United States"][y]
    R(f"| {y} | {s:,} | {us:,} | {s - us} |"); assert s == us, (y, s, us)
R("\nOCR corrections (both justified by that arithmetic):")
for c in corrections: R(f"- {c}")

# ---- 1910-2020 apportionment.csv ----
ap = {}
with open(root / "data/census/apportionment.csv", encoding="utf-8-sig") as f:
    for r in csv.DictReader(f):
        ap[(r["Name"], int(r["Year"]))] = int(r["Resident Population"].replace(",", ""))
R("\n## 2. 1910-2020: apportionment.csv (digital file) - sum of 50 states + DC vs 'United States' row")
R("| Year | Sum of states | U.S. row | Diff |"); R("|---|---|---|---|")
for y in range(1910, 2021, 10):
    s = sum(ap.get((n, y), 0) for n in STATE_NAMES.values()) + sum(
        ap.get((n, y), 0) for n in ("Alaska", "Hawaii") if n not in STATE_NAMES.values())
    s = sum(ap.get((n, y), 0) for n in list(STATE_NAMES.values()) + ["Alaska", "Hawaii"])
    us = ap[("United States", y)]
    R(f"| {y} | {s:,} | {us:,} | {s - us} |"); assert s == us, (y, s, us)

# OCR quality vs digital file where both exist (1910, 1920)
mism = [(k, y) for k, d in forst.items() if k in STATE_NAMES.values() for y in (1910, 1920)
        if (k, y) in ap and d.get(y) != ap[(k, y)]]
R(f"\nOCR vs digital file for 1910 and 1920 (102 state-values): {len(mism)} mismatches" +
  (f" {mism}" if mism else " - the OCR digits are exact where checked."))

# ---- land area ----
area = defaultdict(float)
with open(root / "data/census/2020_Gaz_counties_national.txt", encoding="utf-8") as f:
    rows = csv.reader(f, delimiter="\t"); head = [h.strip() for h in next(rows)]
    ui, ai = head.index("USPS"), head.index("ALAND_SQMI")
    for r in rows: area[r[ui].strip()] += float(r[ai])
pop = {}  # ab -> {year: pop}
for ab, name in STATE_NAMES.items():
    d = {}
    for y in YEARS:
        v = ap.get((name, y)) if y >= 1910 else forst.get(name, {}).get(y)
        if v: d[y] = v
    pop[ab] = d
us_total = {y: (ap[("United States", y)] if y >= 1910 else forst["United States"][y]) for y in YEARS}
dens = {ab: {y: p / area[ab] for y, p in d.items()} for ab, d in pop.items()}
# density check against Census's own published density (apportionment.csv, uses total area) just sanity
R("\n## 3. Density check, 2020 (our land-area density vs Census table density per sq mi)")
for ab in ("NJ", "RI", "TX", "WY"):
    ours = dens[ab][2020]; cen = float(ap_row := 0) if False else None
    with open(root / "data/census/apportionment.csv", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            if r["Name"] == STATE_NAMES[ab] and r["Year"] == "2020": cen = float(r["Resident Population Density"].replace(",", ""))
    R(f"- {STATE_NAMES[ab]}: ours {ours:,.1f} (land area) vs Census {cen:,.1f} (published); differ by water area only")

# ---- centres of population ----
txt = (root / "data/hist/txt/cop2020_doc.txt").read_text(encoding="utf-8").splitlines()
start = next(i for i, l in enumerate(txt) if l.startswith("Table 1. Mean Center"))
cent = {}; us_rows = True
for l in txt[start + 1: start + 60]:
    if l.strip().startswith("Conterminous"): us_rows = False
    m = re.match(r"\s*(\d{4})\s+([\d.]+)\s+([\d.]+)\s+(.*)$", l)
    if not m: continue
    y = int(m.group(1))
    if us_rows or y not in cent:
        if y < 1950 or us_rows:
            loc = re.match(r"([A-Za-z .'-]+ (?:County|Parish|city)?[^,]*,\s*[A-Z]{2})", m.group(4))
            cent[y] = {"lat": float(m.group(2)), "lon": -float(m.group(3)), "loc": loc.group(1).strip() if loc else m.group(4).strip(),
                       "full": m.group(4).strip()}
assert sorted(cent) == YEARS, sorted(cent)
R("\n## 4. Mean centre of population (COP2020_documentation.pdf Table 1)")
for y in YEARS: R(f"- {y}: {cent[y]['lat']}, {cent[y]['lon']} - {cent[y]['loc']}")

json.dump({"years": YEARS, "pop": pop, "dens": dens, "us_total": us_total, "area_sqmi": area,
           "center": cent}, open(root / "data/population.json", "w"), indent=0)
(root / "docs").mkdir(exist_ok=True)
(root / "docs/verify_report.md").write_text("\n".join(report), encoding="utf-8")
print("written")
